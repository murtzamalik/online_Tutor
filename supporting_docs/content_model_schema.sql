-- =============================================================================
-- ONLINE TUTOR PLATFORM — CONTENT & AI-CONTROLS DATA MODEL
-- Scope: qualification x exam board x topic x spec-point x question x mark
--        scheme, plus the mastery/engagement extension tables that back the
--        AI Tutor Intelligence Layer (see AI_Tutor_Intelligence_Layer_
--        Brainstorm.docx, Section 5 "Proposed Technical Architecture").
--
-- Target dialect: Oracle (12c+ IDENTITY columns, VARCHAR2/CLOB/NUMBER).
-- MySQL 8 port notes are called out inline wherever a construct differs —
-- see the "MySQL note" comment on each affected object. In short:
--   * GENERATED BY DEFAULT AS IDENTITY  -> AUTO_INCREMENT
--   * VARCHAR2(n)                       -> VARCHAR(n)
--   * CLOB                              -> LONGTEXT (or JSON where noted)
--   * CHAR(1) CHECK (x IN ('Y','N'))    -> keep as-is, or swap for BOOLEAN
--   * CHECK (x IN (...))                -> supported natively in MySQL 8.0.16+
--
-- Seed reference: GCSE_iGCSE_Chemistry_Pilot_Scaffold.xlsx (Board Topic Map /
-- Board Style Profile tabs) — load AQA(8462), Edexcel(1CH0), OCR Gateway A
-- (J248), Eduqas(C500QS), WJEC Wales, Edexcel Intl(4CH1) and Cambridge
-- IGCSE(0620/0971) as the first `specification` + `spec_topic` rows.
-- =============================================================================


-- =============================================================================
-- SECTION 1 — REFERENCE / LOOKUP TABLES
-- =============================================================================

CREATE TABLE qualification (
    qualification_id   NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR2(20)   NOT NULL UNIQUE,   -- 'ELEVEN_PLUS','GCSE','IGCSE','A_LEVEL'
    display_name        VARCHAR2(100)  NOT NULL,
    typical_age_min      NUMBER(2),
    typical_age_max      NUMBER(2),
    created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE qualification IS 'The four qualification stages the platform covers (client brief Part 1, Section 2).';

CREATE TABLE exam_board (
    board_id            NUMBER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR2(20)   NOT NULL UNIQUE,   -- 'AQA','EDEXCEL','OCR','EDUQAS','WJEC','EDEXCEL_INTL','CAIE'
    display_name         VARCHAR2(100) NOT NULL,
    country_scope        VARCHAR2(50),                    -- 'England','Wales','International'
    official_site_url    VARCHAR2(300),
    created_at            TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE exam_board IS 'Every board the engine must keep a distinct style profile for (brief v3, Part 2: "a generated AQA question should read differently from an Edexcel or OCR one").';

CREATE TABLE subject (
    subject_id           NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR2(30)  NOT NULL UNIQUE,   -- 'CHEMISTRY','PHYSICS','BIOLOGY','COMBINED_SCIENCE','MATHS','ENGLISH_LANGUAGE','ENGLISH_LITERATURE'
    display_name          VARCHAR2(100) NOT NULL,
    is_combined_science    CHAR(1)      DEFAULT 'N' NOT NULL CHECK (is_combined_science IN ('Y','N')),
    created_at             TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE subject IS 'English is split Language/Literature as separate trackable subjects per brief Part 1 Section 2; Combined Science is its own subject, not a bundle.';


-- =============================================================================
-- SECTION 2 — SPECIFICATION (the "offering": one board's version of one
-- subject at one qualification) AND ITS TOPIC TREE
-- =============================================================================

CREATE TABLE specification (
    specification_id    NUMBER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qualification_id    NUMBER          NOT NULL REFERENCES qualification(qualification_id),
    board_id             NUMBER         NOT NULL REFERENCES exam_board(board_id),
    subject_id           NUMBER         NOT NULL REFERENCES subject(subject_id),
    spec_code             VARCHAR2(20)  NOT NULL,          -- '8462','1CH0','J248','C500QS','4CH1','0620'
    title                  VARCHAR2(200) NOT NULL,
    tier_scheme            VARCHAR2(30) NOT NULL CHECK (tier_scheme IN ('FOUNDATION_HIGHER','CORE_EXTENDED','SINGLE_TIER')),
    first_teaching_year     NUMBER(4),
    is_active               CHAR(1)     DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N')),
    created_at               TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_spec_board_subject_qual UNIQUE (qualification_id, board_id, subject_id, spec_code)
);
COMMENT ON TABLE specification IS 'One row per (qualification, board, subject) offering, e.g. "AQA GCSE Chemistry 8462". This is the row the Board Style Profile hangs off.';

CREATE TABLE spec_unit (
    unit_id               NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specification_id      NUMBER        NOT NULL REFERENCES specification(specification_id),
    unit_code               VARCHAR2(30) NOT NULL,          -- 'Paper 1','Unit 2','Component 1'
    unit_name                VARCHAR2(200),
    sequence_order            NUMBER(3),
    assessment_weight_pct      NUMBER(5,2),
    duration_minutes            NUMBER(4),
    is_practical_component       CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_practical_component IN ('Y','N'))
);
COMMENT ON TABLE spec_unit IS 'The paper/component structure per specification, e.g. WJEC Unit 3 Practical Assessment (externally marked, not a content topic).';

CREATE TABLE spec_topic (
    topic_id                NUMBER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specification_id        NUMBER      NOT NULL REFERENCES specification(specification_id),
    unit_id                  NUMBER     REFERENCES spec_unit(unit_id),
    parent_topic_id           NUMBER    REFERENCES spec_topic(topic_id),   -- self-reference: topic -> subtopic -> spec-point
    topic_level                 NUMBER(1) NOT NULL CHECK (topic_level IN (1,2,3)), -- 1=top-level topic, 2=subtopic, 3=spec-point
    topic_number                  VARCHAR2(20),             -- '4.6.1'
    topic_name                     VARCHAR2(500) NOT NULL,
    full_spec_reference               VARCHAR2(200),         -- 'AQA GCSE Chemistry 4.6.1 Rate of reaction' (v3's tagging format)
    separate_science_only             CHAR(1) DEFAULT 'N' NOT NULL CHECK (separate_science_only IN ('Y','N')),
    display_order                       NUMBER(4),
    created_at                            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE spec_topic IS 'Hierarchical topic tree seeded at topic_level=1 from the Board Topic Map tab; content team/AI expand down to topic_level=3 (individual spec points) before question generation begins for that board.';

CREATE INDEX ix_spec_topic_spec ON spec_topic(specification_id);
CREATE INDEX ix_spec_topic_parent ON spec_topic(parent_topic_id);

CREATE TABLE board_style_profile (
    style_profile_id       NUMBER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specification_id       NUMBER       NOT NULL UNIQUE REFERENCES specification(specification_id),
    question_wording_notes  CLOB,                            -- MySQL note: LONGTEXT
    mark_scheme_format_notes CLOB,
    command_words_json         CLOB,                          -- e.g. ["state","explain","calculate","describe and explain"] — MySQL: JSON type
    typical_paper_structure_notes CLOB,
    updated_by                    VARCHAR2(100),
    updated_at                      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE board_style_profile IS 'The per-board "keep a separate style profile" requirement from brief v3 — one row per specification, filled in from the Board Style Profile tab of the pilot scaffold.';


-- =============================================================================
-- SECTION 3 — QUESTIONS & MARKING
-- =============================================================================

CREATE TABLE question (
    question_id              NUMBER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specification_id         NUMBER      NOT NULL REFERENCES specification(specification_id),   -- denormalised for fast filtering
    topic_id                  NUMBER     NOT NULL REFERENCES spec_topic(topic_id),               -- most granular tag (topic_level=3 once tagging is complete)
    source_type                 VARCHAR2(20) NOT NULL CHECK (source_type IN ('REAL_PAST_PAPER','AI_GENERATED','WEB_SOURCED')),
    source_reference               VARCHAR2(300),           -- 'AQA June 2023 Paper 1 Q4' for real papers; generation batch id for AI ones
    tier                              VARCHAR2(20) CHECK (tier IN ('FOUNDATION','HIGHER','CORE','EXTENDED','SINGLE_TIER')),
    difficulty_grade_target             VARCHAR2(10),        -- e.g. '4-5','7-9' — feeds "grade-targeted stretch practice"
    marks_available                       NUMBER(3) NOT NULL,
    question_type                           VARCHAR2(30) NOT NULL CHECK (question_type IN
                                             ('MULTIPLE_CHOICE','SHORT_ANSWER','CALCULATION','EXTENDED_WRITTEN','PRACTICAL_BASED')),
    stem_content                              CLOB NOT NULL,   -- MySQL note: LONGTEXT
    stimulus_image_url                          VARCHAR2(500),
    accepts_answer_modes                          VARCHAR2(30) DEFAULT 'TYPED' NOT NULL,  -- CSV of TYPED,SPOKEN,PHOTO — MySQL note: consider SET() or JSON
    is_paper_authentic_layout                       CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_paper_authentic_layout IN ('Y','N')),
    review_status                                     VARCHAR2(20) DEFAULT 'PENDING_REVIEW' NOT NULL
                                                       CHECK (review_status IN ('PENDING_REVIEW','APPROVED','FLAGGED','REJECTED')),
    reviewed_by                                         VARCHAR2(100),
    reviewed_at                                           TIMESTAMP,
    created_at                                              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE question IS 'Every question the platform can serve, real or AI-generated. source_type + review_status together drive the "from [board] [year] paper" vs AI-generated labelling requirement in brief v3.';

CREATE INDEX ix_question_topic ON question(topic_id);
CREATE INDEX ix_question_spec_tier ON question(specification_id, tier);
CREATE INDEX ix_question_source_review ON question(source_type, review_status);

CREATE TABLE mark_scheme (
    mark_scheme_id         NUMBER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id             NUMBER      NOT NULL UNIQUE REFERENCES question(question_id),
    total_marks               NUMBER(3) NOT NULL,
    marking_points_json          CLOB,   -- structured: [{point, marks, accepted_alternatives[]}] — MySQL: JSON type
    model_answer                   CLOB,
    common_errors_notes              CLOB,
    examiner_style_notes               CLOB,
    created_at                           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE mark_scheme IS 'One mark scheme per question, point-by-point — this is both what the marking engine marks against AND what students self-mark against (brief v3, Cognito-style "reveal the mark scheme" idea).';

CREATE TABLE question_generation_log (
    generation_id            NUMBER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id               NUMBER     NOT NULL UNIQUE REFERENCES question(question_id),
    model_name                  VARCHAR2(100) NOT NULL,
    style_profile_id              NUMBER  REFERENCES board_style_profile(style_profile_id),
    grounding_reference_ids         VARCHAR2(1000),   -- CSV/JSON of real question_ids used as style+content grounding (Self-RAG pattern)
    target_grade                     VARCHAR2(10),
    self_rag_grounding_check_passed    CHAR(1) NOT NULL CHECK (self_rag_grounding_check_passed IN ('Y','N')),
    human_review_required                CHAR(1) NOT NULL CHECK (human_review_required IN ('Y','N')),  -- always 'Y' for EXTENDED_WRITTEN/A-Level per Section 4.4 recommendation
    generated_at                           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE question_generation_log IS 'Audit trail for every AI-generated question: what grounded it and whether it passed the mandatory quality-control review step (brief Part 2 "Quality control note").';


-- =============================================================================
-- SECTION 4 — STUDENTS & ENROLMENT
-- (minimal here — the full account/billing model belongs to the core platform
--  schema from brief Part 1 Section 8; only what the content/AI layer needs
--  to hang off is included)
-- =============================================================================

CREATE TABLE student_profile (
    student_id                NUMBER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_account_id           NUMBER,   -- FK to the core platform's account table (out of scope here)
    display_name                  VARCHAR2(100) NOT NULL,
    year_group                      VARCHAR2(10),   -- 'Y6','Y11','Y13', etc.
    accessibility_profile_json         CLOB,          -- {"dyslexia_font":true,"tts_enabled":true,"extended_time_pct":25} — brief v3 accessibility item
    created_at                            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE student_enrolment (
    enrolment_id                NUMBER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id                   NUMBER    NOT NULL REFERENCES student_profile(student_id),
    specification_id              NUMBER   NOT NULL REFERENCES specification(specification_id),
    target_grade                    VARCHAR2(10),
    exam_date                         DATE,
    enrolled_at                         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_student_spec UNIQUE (student_id, specification_id)
);
COMMENT ON TABLE student_enrolment IS 'Which board/subject/qualification combination a student is actively working on — this is what the onboarding "what do you want to do in this subject" flow writes to.';


-- =============================================================================
-- SECTION 5 — AI-CONTROLS EXTENSION: MASTERY, RESPONSES, ENGAGEMENT
-- (backs Sections 4.1/4.2 of the AI Tutor Intelligence Layer brainstorm)
-- =============================================================================

CREATE TABLE mastery_state (
    mastery_id                   NUMBER    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id                    NUMBER   NOT NULL REFERENCES student_profile(student_id),
    topic_id                       NUMBER  NOT NULL REFERENCES spec_topic(topic_id),
    model_type                       VARCHAR2(10) NOT NULL CHECK (model_type IN ('BKT','DKT','IRT')),
    mastery_probability                 NUMBER(5,4) CHECK (mastery_probability BETWEEN 0 AND 1),  -- BKT/DKT posterior
    irt_ability_estimate                   NUMBER(6,3),   -- theta, IRT only
    attempts_count                           NUMBER(5) DEFAULT 0 NOT NULL,
    fsrs_stability                             NUMBER(8,3),   -- spaced-repetition scheduling state (Section 4.2)
    fsrs_difficulty                              NUMBER(5,3),
    next_review_due_at                             TIMESTAMP,
    last_response_at                                 TIMESTAMP,
    updated_at                                         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_mastery_student_topic_model UNIQUE (student_id, topic_id, model_type)
);
COMMENT ON TABLE mastery_state IS 'Per-student, per-topic mastery estimate that drives the pedagogical strategy controller (direct instruction / worked-example fading / Socratic / spaced retrieval) and the predictive grade-forecast.';

CREATE INDEX ix_mastery_review_due ON mastery_state(next_review_due_at);

CREATE TABLE student_response (
    response_id                  NUMBER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id                    NUMBER    NOT NULL REFERENCES student_profile(student_id),
    question_id                    NUMBER   NOT NULL REFERENCES question(question_id),
    session_id                       VARCHAR2(100) NOT NULL,
    answer_input_mode                  VARCHAR2(10) NOT NULL CHECK (answer_input_mode IN ('TYPED','SPOKEN','PHOTO')),
    raw_answer_content                    CLOB,           -- text, transcript, or a pointer to the stored photo
    is_correct                              CHAR(1) CHECK (is_correct IN ('Y','N')),
    marks_awarded                             NUMBER(4,1),
    marking_mode                                VARCHAR2(25) NOT NULL CHECK (marking_mode IN
                                                 ('AUTO','AI_ASSISTED_HUMAN_REVIEWED','SELF_MARKED')),
    ai_marking_confidence                         NUMBER(5,4),   -- flags low-confidence long-form marks for the human-review queue
    student_confidence_rating                       VARCHAR2(10) CHECK (student_confidence_rating IN ('LOW','MEDIUM','HIGH')),
    time_on_question_ms                               NUMBER(10),
    answer_change_count                                 NUMBER(4) DEFAULT 0 NOT NULL,
    disagree_with_mark_flag                               CHAR(1) DEFAULT 'N' NOT NULL CHECK (disagree_with_mark_flag IN ('Y','N')),
    responded_at                                            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE student_response IS 'Every answer, however it was captured. time_on_question_ms + answer_change_count feed the engagement telemetry (Section 4.1); ai_marking_confidence + marking_mode drive the A-Level human-review queue (Section 4.4); disagree_with_mark_flag is the "disagree with this mark" button from brief v3.';

CREATE INDEX ix_response_student_question ON student_response(student_id, question_id);
CREATE INDEX ix_response_review_queue ON student_response(marking_mode, ai_marking_confidence);

CREATE TABLE engagement_event (
    event_id                     NUMBER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id                    NUMBER    NOT NULL REFERENCES student_profile(student_id),
    session_id                     VARCHAR2(100) NOT NULL,
    event_type                       VARCHAR2(30) NOT NULL CHECK (event_type IN
                                      ('IDLE_DETECTED','FOCUS_SHIFT_OFFERED','CONFUSION_RESCUE_TRIGGERED',
                                       'SURPRISE_QUIZ_SERVED','CONFIDENCE_PROMPT_SHOWN')),
    related_topic_id                   NUMBER REFERENCES spec_topic(topic_id),
    related_question_id                  NUMBER REFERENCES question(question_id),
    event_metadata_json                    CLOB,   -- MySQL note: JSON type
    occurred_at                              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
COMMENT ON TABLE engagement_event IS 'Raw event stream from the engagement telemetry service (Section 4.1) — this is the audit trail behind every focus-shift, confusion-rescue and surprise-quiz trigger, and the input to the weekly parent narrative report.';

CREATE INDEX ix_engagement_student_time ON engagement_event(student_id, occurred_at);


